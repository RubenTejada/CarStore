export const VIEW = { w: 1000, h: 718 };
const LNG = [-72.1, -68.2];
const LAT = [17.4, 20.05];

export const project = (lat: number, lng: number) => ({
  x: ((lng - LNG[0]) / (LNG[1] - LNG[0])) * VIEW.w,
  y: ((LAT[1] - lat) / (LAT[1] - LAT[0])) * VIEW.h,
});

export const unproject = (x: number, y: number) => ({
  lng: LNG[0] + (x / VIEW.w) * (LNG[1] - LNG[0]),
  lat: LAT[1] - (y / VIEW.h) * (LAT[1] - LAT[0]),
});

export const OUTLINE_PATH =
  OUTLINE.map(([lng, lat], i) => {
    const p = project(lat, lng);
    return `${i ? "L" : "M"}${p.x.toFixed(1)} ${p.y.toFixed(1)}`;
  }).join("") + "Z";
